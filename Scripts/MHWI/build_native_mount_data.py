"""Extract the original equipment-parent selectors; never edit LMT/UE assets.

The equipment consumer at 0x14210d360 scans usage 2 records whose *unmasked*
function is 30 or 47, in file order. It samples the truncated layer frame and
accepts Y within an exclusive +/-0.1 range of the requested selector (2 or 3),
or the shared range (3.9, 4.1). The first match wins: function 30 -> mount 2,
function 47 -> mount 1; no match -> fixed descriptor mount 0.

These are parent selectors carried in a scale channel, not equipment stretch.
Native main/sub object identity and the mount transforms are separate evidence.
"""
from __future__ import annotations

import argparse
from bisect import bisect_right
from collections import Counter
import json
from pathlib import Path
import struct

import native_animation_source as source

ROOT = Path(__file__).resolve().parents[2]
JSON_PATH = ROOT / 'Tools/MHW/native-mount-curves.json'
CPP_PATH = ROOT / 'Source/IntroCpp/MHWI/MHWINativeMountData.inl'
F32 = struct.Struct('<f')


def f32(value):
    return F32.unpack(F32.pack(value))[0]


def choose_mount(ordered_tracks, frame, selector):
    """Match the native first-success scan, without pose-binding deduplication."""
    low, high = f32(selector - f32(.1)), f32(selector + f32(.1))
    for function, curve in ordered_tracks:
        value = f32(curve.raw_sample(frame)[1])
        if low < value < high or f32(3.9) < value < f32(4.1):
            return 2 if function == 30 else 1
    return 0


def sample_keys(keys, frame):
    index = max(0, bisect_right([key['frame'] for key in keys], frame) - 1)
    return keys[index]['main'], keys[index]['sub']


def extract():
    reader, pose = source.native_modules()
    banks, clips = [], []
    checked_frames = 0
    codecs = Counter()
    for bank_index, (family, path) in enumerate(source.SOURCES.items()):
        bank = reader.read_lmt_file(path)
        if bank.header.version != 95:
            raise ValueError(f'{family}: only native v95 sampler qualified')
        banks.append(dict(name=family, version=bank.header.version, **source.evidence(path)))
        for action in bank.actions:
            ordered, track_evidence = [], []
            for index, track in enumerate(action.tracks):
                h = track.header
                if h.usage != 2 or h.bone_id not in (30, 47):
                    continue
                curve = pose.compile_pose_curve(track)
                ordered.append((h.bone_id, curve))
                codecs[h.buffer_type] += 1
                track_evidence.append(dict(index=index, function=h.bone_id,
                    codec=h.buffer_type, weight=h.weight, joint_type=h.joint_type,
                    buffer_offset=h.buffer_offset, buffer_bytes=h.buffer_size,
                    key_frames=curve.frames, scale_y_values=[value[1] for value in curve.values]))
            keys = []
            for frame in range(action.header.frame_count):
                main, sub = (choose_mount(ordered, frame, selector) for selector in (2., 3.))
                if not keys or (main, sub) != (keys[-1]['main'], keys[-1]['sub']):
                    keys.append(dict(frame=frame, main=main, sub=sub))
            if not keys:
                # Empty source clips are not runnable and have no sampled frame.
                continue
            # Check every compact interval against a fresh source evaluation.
            for frame in range(action.header.frame_count):
                expected = tuple(choose_mount(ordered, frame, selector) for selector in (2., 3.))
                if sample_keys(keys, frame) != expected:
                    raise AssertionError((family, action.id, frame, expected))
                checked_frames += 1
            clips.append(dict(clip=f'{family}_{action.id:03}', bank=family, bank_index=bank_index,
                motion=action.id, frames=action.header.frame_count,
                loop_frame=action.header.loop_frame, flags2=action.header.flags2,
                ordered_control_tracks=track_evidence, keys=keys))
    return dict(schema_version=1, source_fps=60,
        interpretation='Native equipment selector scan; main/sub identity and transform are separate evidence',
        original_consumer='0x14210d360', sampler='0x142234010',
        rules=dict(function_to_mount={'30': 2, '47': 1}, main_selector=2., sub_selector=3.,
            epsilon=f32(.1), shared_exclusive_range=[f32(3.9), f32(4.1)],
            frame='truncate nonnegative native layer frame', ordering='first matching original record'),
        sources=banks, clips=clips,
        verification=dict(checked_source_frames=checked_frames, clips=len(clips),
            interval_keys=sum(len(c['keys']) for c in clips),
            control_record_codecs=dict(sorted(codecs.items())), passed=True))


def cpp_text(report):
    lines = ['// Generated by Scripts/MHWI/build_native_mount_data.py; do not hand edit.',
        '// Original v95 LMT usage-2/function-30/47 scan: 0x14210d360.',
        '// Mount 0=fixed descriptor, 1=function 47, 2=function 30.',
        '// Main/sub identity is defined by the equipment caller, not by this table.',
        'struct FMHWINativeMountSelection { uint8 Main = 0; uint8 Sub = 0; };',
        'namespace MHWINativeMountData', '{',
        '    struct FKey { int32 Frame; uint8 Main; uint8 Sub; };',
        '    struct FClip { uint8 Bank; int32 Motion; int32 Frames; int32 First; int32 Count; };',
        '    static constexpr FKey Keys[] =', '    {']
    for clip in report['clips']:
        lines.append(f"        // {clip['clip']}")
        lines.extend(f"        {{{key['frame']}, {key['main']}, {key['sub']}}}," for key in clip['keys'])
    lines += ['    };', '    static constexpr FClip Clips[] =', '    {']
    start = 0
    for clip in report['clips']:
        lines.append(f"        {{{clip['bank_index']}, {clip['motion']}, {clip['frames']}, {start}, {len(clip['keys'])}}},")
        start += len(clip['keys'])
    lines += ['    };', '}', '',
        '/** False means an unknown/non-finite source; no fallback is fabricated. */',
        'static bool SampleMHWINativeMount(FName Bank, int32 Motion, float Frame, FMHWINativeMountSelection& Out)',
        '{', '    if (!FMath::IsFinite(Frame) || Frame < 0.f) return false;',
        '    static const FName WeaponBank(TEXT("w03_00"));',
        '    static const FName CommonBank(TEXT("co00_00"));',
        '    const int32 BankIndex = Bank == WeaponBank ? 0 : (Bank == CommonBank ? 1 : INDEX_NONE);',
        '    if (BankIndex == INDEX_NONE) return false;',
        '    const int32 NativeFrame = FMath::TruncToInt(Frame);',
        '    for (const MHWINativeMountData::FClip& Clip : MHWINativeMountData::Clips)',
        '    {', '        if (Clip.Bank != BankIndex || Clip.Motion != Motion) continue;',
        '        const MHWINativeMountData::FKey* Selected = &MHWINativeMountData::Keys[Clip.First];',
        '        for (int32 Index = 1; Index < Clip.Count; ++Index)',
        '        {', '            const auto& Key = MHWINativeMountData::Keys[Clip.First + Index];',
        '            if (Key.Frame > NativeFrame) break;', '            Selected = &Key;', '        }',
        '        Out = {Selected->Main, Selected->Sub};', '        return true;', '    }',
        '    return false;', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check reproducibility without writing')
    args = parser.parse_args()
    report = extract()
    outputs = {JSON_PATH: json.dumps(report, indent=2) + '\n', CPP_PATH: cpp_text(report)}
    for path, value in outputs.items():
        if args.check:
            if path.read_text(encoding='utf8') != value:
                raise SystemExit(f'Generated output differs: {path}')
        else:
            path.write_text(value, encoding='utf8')
    print(json.dumps(report['verification']))
    focus = ('w03_00_001', 'w03_00_002', 'w03_00_003', 'w03_00_102',
             'w03_00_306', 'w03_00_307', 'w03_00_308')
    for clip in report['clips']:
        if clip['clip'] in focus:
            print(clip['clip'], clip['keys'])


if __name__ == '__main__':
    main()
