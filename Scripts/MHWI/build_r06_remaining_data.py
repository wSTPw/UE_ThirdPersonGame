"""Generate B10 native source-owner data. Authoring, never a test suite."""
import json
from pathlib import Path
from audit_native_timing import parse_lmt, names
from native_connector_source import parse_mbd

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT/'Saved/MHWIRestoration/B10-20261025'


def run():
    labels = ROOT/'Saved/MHWIImport/SourceFidelity-20261023/timing-FreeHK-upstream/MHW-Free-HyperKinetics-main/struct'
    base = ROOT/'ArtSource/ThirdParty/MHWLongSword/nativePC/hm'
    banks = {bank:parse_lmt(base/relative, names(labels/'TIMLTimelineParam.txt'), names(labels/'TIMLDatatypes.txt',True))
             for bank,relative in (('w03_00','wp/wp03/mot/w03_00/w03_00.lmt'),('co00_00','common/mot/co00_00/co00_00.lmt'))}
    bindings = [dict(identity=[3,30+i],bank='w03_00',motion=61+i,node=26) for i in range(3)]
    bindings += [dict(identity=[1,action],bank='co00_00',motion=70+i,node=27) for i,action in enumerate((103,110,115))]
    # LS's canonical standing hit reactions are explicitly configured by
    # 14187cb80 -> 14187a7c0; CreepSingleMotion(34) is configured to c0dd.
    bindings += [dict(identity=[3,34],bank='w03_00',motion=221,node=43)]
    nodes = {104:66,105:70,106:69,107:67,108:71,109:72,110:68,111:73,112:74}
    for action in range(104,113):
        stage,direction=divmod(action-104,3)
        bindings.append(dict(identity=[3,action],bank='w03_00',motion=338+stage*3+(0,2,1)[direction],node=nodes[action]))
    common = parse_mbd((base/'common/mot/co00_00/co00_00.mbd').read_bytes())
    authored = json.loads((ROOT/'ArtSource/ThirdParty/MHWLongSword/R06Remaining-20261025/export-manifest.json').read_text())
    wanted = {(r['bank'],r['motion']) for r in authored['clips']}
    wanted.update(('w03_00',n) for n in (111,114,117,118,119,120,121,122,123,124,125,129,131,132,152,357,358,359,360,361,362,363,364,365,366,367))
    weapons, triggers, common_infos = [], [], []
    for bank,data in banks.items():
        for motion in data['entries']:
            if bank=='co00_00': common_infos.append(dict(motion=motion['index'],frames=motion['source_frame_count'],loop=motion['source_loop_frame']))
            if (bank,motion['index']) not in wanted: continue
            for group in motion['groups']:
                for track in group['tracks']:
                    if group['name']!='nTimelineParam::PlMotionCommon':continue
                    if track['name']=='mWeaponMotionNo':
                        weapons += [dict(bank=bank,motion=motion['index'],frame=k['frame'],value=k['value']) for k in track['keys']]
                    if track['name']=='mTrigger' and 332 <= motion['index'] <=349:
                        triggers += [dict(motion=motion['index'],frame=k['frame']) for k in track['keys'] if int(k['value'])&1]
    def f(value):
        value=format(float(value),'.9g')
        return value+('.0' if '.' not in value and 'e' not in value.lower() else '')+'f'
    lines=['// Generated by build_r06_remaining_data.py; source facts, not test results.',
           '#pragma once','namespace MHWI::Native {','inline const FSourceBinding SourceBindings[] = {']
    lines += ['    {{%d, %d}, FName(TEXT("%s")), %d, %d},' % (*r['identity'],r['bank'],r['motion'],r['node']) for r in bindings]
    lines += ['};','inline const FMotionInfo CommonSourceMotions[] = {']
    lines += ['    {%d, %d, %d},' % (r['motion'],r['frames'],r['loop']) for r in common_infos]
    lines += ['};','inline const FSourceWeaponKey SourceWeaponKeys[] = {']
    lines += ['    {FName(TEXT("%s")), %d, %s, %d},' % (r['bank'],r['motion'],f(r['frame']),r['value']) for r in weapons]
    lines += ['};','inline const FSourceTrigger SlingerTriggers[] = {']
    lines += ['    {%d, %s},' % (r['motion'],f(r['frame'])) for r in triggers]
    lines += ['};','inline const FBlendEntry CommonSourceBlends[] = {']
    for entry in common['entries']:
        for b in entry['blocks']:
            bank=b['declaration'].replace('\\','\\\\').replace('"','\\"')
            lines += ['    {%d, %d, FName(TEXT("%s")), %s, %d, %d, %d, %s, %d, %d},' % (
                entry['index'],b['animation_id'],bank,f(b['unknown4']),b['start_frame'],b['interpolation_point'],
                b['overlap_blending'],f(b['unknown8']),b['one0'],b['min1'])]
    lines += ['};','}']
    (ROOT/'Source/IntroCpp/MHWI/MHWIR06SourceData.inl').write_text('\n'.join(lines)+'\n',encoding='utf8')
    record=dict(schema=1,status='source_generated_not_tested',tests_executed=False,bindings=bindings,
                weapon_keys=weapons,slinger_triggers=triggers,common_motion_count=len(common_infos),
                evidence='Saved/MHWIRestoration/B10-20261025/remaining-native-functions.json',
                impact_configuration=['0x14187cb9a','0x14187cbcc','0x14187a849','0x14187a89d','0x14187a8ee'],
                recoil_configuration='0x14187cc99',
                slinger_variants=['0x1417fe370','0x1417fe3e0','0x1417fe450'],
                boundary='Canonical LS standing reactions are production owners. Full environmental/walk/sit/mirrored reaction selection belongs to R24, not an invented source alias.')
    (ROOT/'Tools/MHW/native-r06-source-owners.json').write_text(json.dumps(record,indent=2)+'\n')
    print(json.dumps(dict(generated=True,source_bindings=len(bindings),tests_executed=False)))


if __name__=='__main__':run()
